/** The work-item code a hand id became, or undefined when the hand table never had that id. */
export function backlogCodeOf(backlogId: string): string | undefined {
	return BACKLOG_MIGRATION.find((row) => row.backlogId === backlogId)?.input.code;
}

/** The hand id a work-item code came from, for the diff and for a lane that names its origin. */
export function backlogIdOf(code: string): string | undefined {
	return BACKLOG_MIGRATION.find((row) => row.input.code === code)?.backlogId;
}

/** The table as records, built by the same function createWorkItem uses, without writing a store. */
export function backfillRecords(): WorkItemRecord[] {
	return BACKLOG_MIGRATION.map((row) => buildWorkItemRecord(row.input, { by: "operator-shell", at: BACKLOG_BACKFILLED_AT }));
}

/** One record as one hand-table row: the table's own column names, so the two tables are comparable. */
export function backlogRow(record: WorkItemRecord): Record<string, string> {
	return {
		"id": record.code,
		"outcome": record.heading,
		"state": record.state,
		"brief / source": record.source,
		"deps": record.dependencies.length === 0 ? "none" : record.dependencies.join(", "),
		"sprint goal": record.goal,
	};
}

/**
 * The generated backlog: the records rendered into the hand table's columns. It is a view, never an
 * edit target (spec §7b: a generated view is never edited by hand).
 */
export function renderGeneratedBacklog(records: readonly WorkItemRecord[]): string {
	const ordered = [...records].sort((left, right) => left.code.localeCompare(right.code));
	const lines = [
		"# Backlog — generated from the work-item records",
		"",
		"Rendered by `muster schema work-item --backlog` from the work-item store, or by",
		"`muster schema work-item --backlog --backfill` from the retired hand table's rows, which this mapping",
		"carried over at the cutover of 2026-10-29.",
		`${ordered.length} record${ordered.length === 1 ? "" : "s"}. The records are the truth; this file is never edited by hand (spec §7b).`,
		"",
		renderBacklogTable(BACKLOG_COLUMNS, ordered.map(backlogRow)),
	];
	return lines.join("\n");
}
